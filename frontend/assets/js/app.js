function aplicarIdioma(idioma) {
  traducirInterfaz(idioma);
  traducirElementosCompuestos(idioma);
}

function traducirElementosCompuestos(idioma) {
  const mensajes = I18N[idioma] || I18N.es;
  document.querySelectorAll('[data-i18n-label]').forEach((elemento) => {
    const key = elemento.dataset.i18nLabel;
    const texto = mensajes[key];
    if (!texto) return;
    const nodo = Array.from(elemento.childNodes).find((n) => n.nodeType === Node.TEXT_NODE && n.textContent.trim());
    if (nodo) nodo.textContent = `${texto} `;
  });
  document.querySelectorAll('[data-i18n-prefix]').forEach((elemento) => {
    const key = elemento.dataset.i18nPrefix;
    const texto = mensajes[key];
    if (!texto) return;
    const nodo = Array.from(elemento.childNodes).find((n) => n.nodeType === Node.TEXT_NODE && n.textContent.trim());
    if (nodo) nodo.textContent = `${texto} `;
  });
  document.querySelectorAll('[data-i18n-default]').forEach((elemento) => {
    const key = elemento.dataset.i18nDefault;
    const texto = mensajes[key];
    if (texto) elemento.textContent = texto;
  });
}

